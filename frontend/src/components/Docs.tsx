// Printable documents: challan / transfer slip, unit QR labels, bay card.
import type { ReactNode } from 'react';
import type { Doc, Position } from '../api';
import { useWms } from '../wms';
import { QR, docQR, locQR, unitQR } from './QR';

const TITLE = { RCV: 'Receiving Challan', DSP: 'Dispatch Challan', TRF: 'Transfer Slip' } as const;
const kg = (n: number) => `${(Math.round(n * 10) / 10).toLocaleString('en-IN')} kg`;

export function DocPaper({ doc }: { doc: Doc }) {
  const partyK = doc.type === 'RCV' ? 'Supplier' : doc.type === 'DSP' ? 'Receiver' : 'Type';
  const refK = doc.type === 'RCV' ? "Supplier's ref." : doc.type === 'DSP' ? 'Destination' : 'Reason';
  return (
    <div className="paper">
      <div className="doc-top">
        <div><div className="co">Azneo Limited</div><div className="co-sub">{doc.warehouse.name} Warehouse<br />{doc.warehouse.address}</div></div>
        <div className="dt"><div className="t">{TITLE[doc.type]}</div><div className="no">{doc.no}</div></div>
      </div>
      <div className="kv">
        <div><div className="k">Date</div><div className="v">{doc.docDate.slice(0, 10)} · {new Date(doc.createdAt).toLocaleTimeString('en-GB', { hour: '2-digit', minute: '2-digit' })}</div></div>
        <div><div className="k">{partyK}</div><div className="v">{doc.party}</div></div>
        <div><div className="k">{refK}</div><div className="v">{doc.reference || '—'}</div></div>
        <div><div className="k">Prepared by</div><div className="v">{doc.preparedBy}</div></div>
        {doc.type === 'RCV' && <div><div className="k">Placed in</div><div className="v">Receiving Area → shelved via Put-away</div></div>}
        {doc.type === 'TRF' && <div><div className="k">Moved to</div><div className="v">{doc.toCode}</div></div>}
      </div>
      <table>
        <thead><tr><th>#</th><th>Product</th><th className="num">Qty</th>{doc.type !== 'RCV' && <th>From</th>}<th>Unit IDs</th></tr></thead>
        <tbody>
          {doc.lines.map((l, i) => (
            <tr key={l.sku}>
              <td>{i + 1}</td>
              <td><b>{l.name}</b><div style={{ fontSize: 10.5, color: '#6b7671', fontFamily: 'IBM Plex Mono, monospace' }}>{l.sku}</div></td>
              <td className="num">{l.uids.length}</td>
              {doc.type !== 'RCV' && <td className="ids">{Object.entries(l.from).map(([f, n]) => `${f} (${n})`).join(', ') || '—'}</td>}
              <td className="ids">{l.byVin ? 'VIN: ' : ''}{l.uids.join(', ')}</td>
            </tr>
          ))}
          <tr className="tot"><td /><td>Total · {kg(doc.totalKg)}</td><td className="num">{doc.units}</td>{doc.type !== 'RCV' && <td />}<td /></tr>
        </tbody>
      </table>
      <div className="foot">
        <QR text={docQR(doc.no)} size={78} />
        <div className="sign">
          <div><div className="ln" />Prepared by</div><div><div className="ln" />Checked by</div><div><div className="ln" />{doc.type === 'DSP' ? 'Received by' : 'Authorised by'}</div>
        </div>
      </div>
      <div className="gen">Generated by Azneo WMS · No product moves without a challan</div>
    </div>
  );
}

export function LabelsSheet({ doc }: { doc: Doc }) {
  return (
    <div className="label-sheet">
      {doc.lines.flatMap((l) => l.uids.map((uid) => (
        <div key={uid} className="qr-label">
          <div className="co">AZNEO WMS</div>
          <QR text={unitQR(uid)} size={92} />
          <div className="uid">{l.byVin ? 'VIN ' : ''}{uid}</div>
          <div className="pn">{l.name}</div>
          <div className="ref">{doc.no}</div>
        </div>
      )))}
    </div>
  );
}

export function BayCard({ wh, code, pos }: { wh: string; code: string; pos: Pick<Position, 'description' | 'items' | 'qty' | 'kg' | 'shelf'> }) {
  return (
    <div className="bay-card">
      <div className="top">
        <div><div className="code">{code}</div><div className="desc">{pos.description}</div></div>
        <QR text={locQR(wh, code)} size={64} />
      </div>
      {pos.items.length
        ? <table><thead><tr><th>Item</th><th className="num">Qty</th><th className="num">Weight</th></tr></thead>
          <tbody>{pos.items.map((i) => <tr key={i.sku}><td>{i.name}</td><td className="num">{i.qty}</td><td className="num">{kg(i.kg)}</td></tr>)}</tbody></table>
        : <div style={{ fontSize: 12, color: '#6b7671', padding: '6px 0' }}>Empty</div>}
      <div className="totals">
        <span>Items: {pos.items.length}</span><span>Qty: {pos.qty}</span><span>Weight: {kg(pos.kg)}</span>
        {pos.shelf && <span>Shelf: {Math.round(pos.shelf.usedKg)}/{pos.shelf.capKg} kg</span>}
      </div>
      <div className="upd">Printed {new Date().toLocaleString('en-GB')} from Azneo WMS</div>
    </div>
  );
}

export function LocationLabel({ wh, code, sub }: { wh: string; code: string; sub: string }) {
  return (
    <div className="qr-label" style={{ width: 230, margin: '20px auto' }}>
      <div className="co">AZNEO WMS · LOCATION</div>
      <QR text={locQR(wh, code)} size={150} />
      <div className="uid" style={{ fontSize: 17 }}>{code}</div>
      <div className="pn">{sub}</div>
    </div>
  );
}

export function Modal({ title, children, actions, onClose }: { title: string; children: ReactNode; actions?: ReactNode; onClose: () => void }) {
  return (
    <div className="modal-wrap" onClick={(e) => e.target === e.currentTarget && onClose()}>
      <div className="modal" role="dialog" aria-modal="true" aria-label={title}>
        <div className="modal-head"><h2>{title}</h2><button className="x-btn" onClick={onClose} aria-label="Close">×</button></div>
        <div className="modal-body">{children}</div>
        <div className="modal-foot">{actions}<button className="btn" onClick={onClose}>Close</button></div>
      </div>
    </div>
  );
}

/** A challan on screen with Print buttons (and QR labels for receipts). */
export function DocModal({ doc, onClose, extra }: { doc: Doc; onClose: () => void; extra?: ReactNode }) {
  const { print } = useWms();
  return (
    <Modal title={`${TITLE[doc.type]} ${doc.no}`} onClose={onClose} actions={<>
      <button className="btn btn-primary" onClick={() => print(<DocPaper doc={doc} />)}>Print {doc.type === 'TRF' ? 'slip' : 'challan'}</button>
      {doc.type === 'RCV' && <button className="btn" onClick={() => print(<LabelsSheet doc={doc} />)}>Print QR labels ({doc.units})</button>}
      {extra}
    </>}>
      <DocPaper doc={doc} />
    </Modal>
  );
}
